import { chromium, devices } from 'playwright';
const b=await chromium.launch({executablePath:'/opt/pw-browsers/chromium-1243/chrome-linux64/chrome',args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--no-sandbox']});
const ctx=await b.newContext({...devices['Pixel 7']});const p=await ctx.newPage();
p.on('pageerror',e=>console.log('PAGEERR',e.message,(e.stack||'').split('\n').slice(0,4).join('|')));p.on('console',m=>{if(['error','warning'].includes(m.type()))console.log(m.type().toUpperCase(),m.text().slice(0,200))});
await p.goto('http://localhost:4173/');await p.waitForTimeout(8000);
console.log(await p.evaluate(()=>({state:window.__game?.state,w:innerWidth,h:innerHeight,t:document.body.innerText.slice(0,80)})));
await p.tap('text=Begin').catch(e=>console.log('TAPERR',e.message.slice(0,100)));
await p.waitForTimeout(25000);
console.log(await p.evaluate(()=>({state:window.__game?.state,locked:!!document.pointerLockElement})));
await p.screenshot({path:'/tmp/m.png',timeout:120000});await b.close();
